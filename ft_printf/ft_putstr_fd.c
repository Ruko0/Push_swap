#include "ft_printf.h"

int	pf_putstr_fd(char *s, int fd)
{
	int	i;

	i = 0;
	if (!s)
	{
		return (write(fd, "(null)", 6));
	}
	while (*s)
	{
		write(fd, s, 1);
		s++;
		i++;
	}
	return (i);
}
